const PACKS = { en: UI_EN, th: UI_TH, km: UI_KM }

/** Which languages this build offers, in the order the toggle cycles them. */
export const UI_LOCALES = Object.keys(PACKS)

export function makeUI(locale) {
  const pack = PACKS[locale] || UI_EN
  return (key, params) => {
    const s = pack[key] ?? UI_EN[key] ?? key
    return params
      ? String(s).replace(/\{(\w+)\}/g, (m, p) => (p in params ? String(params[p]) : m))
      : s
  }
}
